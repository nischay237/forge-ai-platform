package com.forge.platform.common;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI forgeOpenApi() {
        return new OpenAPI()
            .info(new Info()
                .title("FORGE — AI Software Engineering Intelligence Platform API")
                .version("1.0.0")
                .description("Multi-tenant engineering intelligence API: GitHub integration, JavaParser AST Code Intelligence, AI Pull Request Reviews, Security Scanning, CI Failure Diagnosis, and Analytics."))
            .addSecurityItem(new SecurityRequirement().addList("bearerAuth"))
            .components(new Components()
                .addSecuritySchemes("bearerAuth", new SecurityScheme()
                    .name("bearerAuth")
                    .type(SecurityScheme.Type.HTTP)
                    .scheme("bearer")
                    .bearerFormat("JWT")));
    }
}
